/** topicId → { sectionId, moduleId? }. Нужен для хлебных крошек и поиска. */
export const TOPIC_INDEX = (() => {
  const index = {};
  for (const s of SECTIONS) {
    if (s.page) index[s.page] = { sectionId: s.id };
    for (const id of s.topics || []) index[id] = { sectionId: s.id };
    for (const m of s.modules || []) {
      if (m.page) index[m.page] = { sectionId: s.id, moduleId: m.id };
      for (const id of m.topics || []) index[id] = { sectionId: s.id, moduleId: m.id };
    }
  }
  return index;
})();

export const findSection = (id) => SECTIONS.find((s) => s.id === id) || null;

export const findModule = (sectionId, moduleId) =>
  (findSection(sectionId)?.modules || []).find((m) => m.id === moduleId) || null;

export const topicTitle = (id) => TOPICS[id]?.title || id;

/** Разделы одной группы, в порядке объявления. */
export const sectionsOf = (group) => SECTIONS.filter((s) => s.group === group);

/** Все темы раздела подряд: страница, плоский список или темы всех модулей. */
export const sectionTopics = (s) => {
  if (s.page) return [s.page];
  if (s.modules) return s.modules.flatMap((m) => (m.page ? [m.page] : m.topics || []));
  return s.topics || [];
};

export const sectionSize = (s) => sectionTopics(s).length;

/** Включены ли карточки на странице этой темы (флаг стоит на разделе). */
export const hasCards = (topicId) => !!findSection(TOPIC_INDEX[topicId]?.sectionId)?.cards;

/** Тема без единого заполненного блока — заглушка, и страница это говорит прямо. */
export const isStub = (t) => !['points', 'terms', 'commands', 'code', 'qa', 'links']
  .some((k) => t?.[k]?.length);
